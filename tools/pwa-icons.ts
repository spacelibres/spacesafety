/**
 * Render the PWA icons from the VI icon master.
 *
 * The manifest needs raster icons: Chrome will not offer "install to desktop"
 * without them, and an SVG entry alone cannot satisfy the maskable variants.
 * Rather than invent artwork, this screenshots the approved vector master at the
 * sizes the manifest declares — the same master the sidebar and the favicon use,
 * so the installed app cannot drift from the brand.
 *
 *   npm run pwa:icons
 *
 * Output is committed (`public/pwa/*.png`, a few kilobytes each) so a normal
 * build needs no browser. Re-run this only when the master or the palette changes.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import puppeteer from "puppeteer-core";

import { ELECTRIC_ORBIT } from "../src/lib/vi/palette";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(ROOT, "public", "pwa");

/** The sizes the install prompt and the splash screen ask for. */
const SIZES = [192, 512] as const;

/**
 * Padding for the maskable variants.
 *
 * A maskable icon is cropped to whatever shape the platform uses, so the mark has
 * to sit inside the central safe zone. 12% per side keeps the entire mark inside
 * it while leaving the canvas full-bleed, which is what the platform expects.
 */
const MASKABLE_PADDING = 0.12;

export class PwaIcons {
  async run(): Promise<number> {
    mkdirSync(OUT, { recursive: true });

    // Inline the master instead of fetching it: the icon must not depend on a
    // running server, and an inline <svg> cannot fail to load mid-screenshot.
    const svg = readFileSync(join(ROOT, "public", "vi", "icon-primary-dark.svg"), "utf8");
    const background = ELECTRIC_ORBIT.deep;

    const browser = await puppeteer.launch({
      executablePath: process.env.CHROME_PATH ?? "/usr/bin/google-chrome",
      headless: true,
      args: ["--no-sandbox", "--disable-dev-shm-usage"],
    });
    const page = await browser.newPage();

    try {
      for (const size of SIZES) {
        for (const variant of ["any", "maskable"] as const) {
          const pad = variant === "maskable" ? Math.round(size * MASKABLE_PADDING) : 0;
          const inner = size - pad * 2;
          await page.setViewport({ width: size, height: size, deviceScaleFactor: 1 });
          await page.setContent(
            `<!doctype html><html><head><meta charset="utf-8"><style>
               html,body{margin:0;padding:0;width:${size}px;height:${size}px;background:${background};}
               .mark{display:block;width:${inner}px;height:${inner}px;margin:${pad}px;}
               .mark svg{display:block;width:100%;height:100%;}
             </style></head><body><div class="mark">${svg}</div></body></html>`,
            { waitUntil: "load" },
          );
          const file = join(OUT, `icon-${size}-${variant}.png`);
          await page.screenshot({ path: file as `${string}.png` });
          console.log(`  ok   icon-${size}-${variant}.png  ${readFileSync(file).length} B`);
        }
      }

      const readme = [
        "# PWA icons",
        "",
        "Generated by `npm run pwa:icons` from `public/vi/icon-primary-dark.svg` —",
        "the same VI master the sidebar and favicon use. Do not edit the PNGs by hand:",
        "re-run the script after changing the master or the palette.",
        "",
        ...SIZES.flatMap((size) => [
          `- \`icon-${size}-any.png\` — ${size}x${size}, maskable: no`,
          `- \`icon-${size}-maskable.png\` — ${size}x${size}, mark inset ${MASKABLE_PADDING * 100}% for the platform's safe zone`,
        ]),
        "",
      ].join("\n");
      writeFileSync(join(OUT, "README.md"), readme, "utf8");
      return 0;
    } finally {
      await browser.close();
    }
  }
}

async function main(): Promise<void> {
  console.log("\nPWA icons\n");
  const code = await new PwaIcons().run();
  console.log(code === 0 ? "\n图标已写入 public/pwa/\n" : "\n生成失败\n");
  process.exit(code);
}

void main();
