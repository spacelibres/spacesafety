import { NextResponse } from "next/server";

import { listObjects, type ObjectFilters } from "@/lib/queries";
import { listPublishedConjunctions } from "@/lib/queries";
import { countWideObjects, listWideObjects, wideCatalogueAvailable } from "@/lib/wide-catalogue";

export const dynamic = "force-dynamic";

/**
 * Downloads for the pages that show a table.
 *
 * ## Why this is not under `/api/v1`
 *
 * Everything under `/api/v1` is the vendor's contract and is authenticated by
 * client certificate. These exports are a convenience for the reader of a page —
 * "give me this table as a file" — and the pages themselves are already public on
 * this deployment, so putting them behind the API's mTLS would mean the download
 * button works for scripts and not for the person clicking it.
 *
 * They are documented as this deployment's extension in `/docs`, together with
 * `/api/models/*` and `/api/v1/catalogue/choice`.
 *
 * ## Why CSV is generated by hand
 *
 * The widest export is 42 427 rows × 10 columns; a CSV library would add a
 * dependency for quoting rules that fit in one function. The BOM matters: Excel
 * reads a UTF-8 CSV without it as the local ANSI codepage, which turns every
 * non-ASCII object name into mojibake.
 */
const MAX_ROWS = 50_000;

/** RFC 4180 quoting: wrap when the value contains a delimiter, quote or newline. */
function csvCell(value: unknown): string {
  if (value === null || value === undefined) return "";
  const text = String(value);
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

function toCsv(header: string[], rows: Array<Array<unknown>>): string {
  const lines = [header.map(csvCell).join(",")];
  for (const row of rows) lines.push(row.map(csvCell).join(","));
  // BOM so a spreadsheet opens it as UTF-8.
  return `\ufeff${lines.join("\r\n")}\r\n`;
}

/** `filename="…"` plus the RFC 5987 form, so a non-ASCII name survives UTF-8 headers. */
function attachment(name: string): string {
  const ascii = name.replace(/[^\x20-\x7e]/g, "_");
  return `attachment; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(name)}`;
}

function stamp(): string {
  return new Date().toISOString().slice(0, 19).replace(/[:T]/g, "-");
}

export async function GET(request: Request): Promise<Response> {
  const url = new URL(request.url);
  const what = url.searchParams.get("what") ?? "objects";
  const format = url.searchParams.get("format") ?? "csv";

  if (format !== "csv" && format !== "json") {
    return NextResponse.json(
      { error: "format must be csv or json", parameter: "format" },
      { status: 400 },
    );
  }

  if (what === "objects") {
    const filters: ObjectFilters = {
      alive: url.searchParams.get("alive") === "true" ? true : url.searchParams.get("alive") === "false" ? false : undefined,
      nameContains: url.searchParams.get("name")?.trim() || undefined,
      noradId: /^[0-9]{1,9}$/.test(url.searchParams.get("norad") ?? "")
        ? Number(url.searchParams.get("norad"))
        : undefined,
    };
    const rows = listObjects(MAX_ROWS, { key: "objectName", dir: "asc" }, filters);
    if (format === "json") {
      return NextResponse.json(
        { exported_at: new Date().toISOString(), what, count: rows.length, result: rows },
        { headers: { "content-disposition": attachment(`objects-${stamp()}.json`) } },
      );
    }
    const csv = toCsv(
      [
        "id",
        "object_name",
        "norad_id",
        "operator",
        "object_class",
        "country",
        "cospar_id",
        "mass_kg",
        "hard_body_radius_km",
        "alive",
        "maneuverable",
      ],
      rows.map((o) => [
        o.id,
        o.objectName,
        o.noradId,
        o.operatorName,
        o.objectClass,
        o.country,
        o.cosparId,
        o.massKg,
        o.hardBodyRadius,
        o.alive,
        o.maneuverability,
      ]),
    );
    return new Response(csv, {
      headers: {
        "content-type": "text/csv; charset=utf-8",
        "content-disposition": attachment(`objects-${stamp()}.csv`),
      },
    });
  }

  if (what === "catalogue") {
    if (!wideCatalogueAvailable()) {
      return NextResponse.json(
        { error: "wide catalogue not built; run `npx tsx tools/build-wide-catalogue.ts`" },
        { status: 503 },
      );
    }
    const filters = {
      nameContains: url.searchParams.get("q")?.trim() || undefined,
      noradId: /^[0-9]{1,9}$/.test(url.searchParams.get("norad") ?? "")
        ? Number(url.searchParams.get("norad"))
        : undefined,
    };
    const matched = countWideObjects(filters);
    const rows = listWideObjects({ ...filters, limit: 1000, offset: 0 });
    if (format === "json") {
      return NextResponse.json(
        {
          exported_at: new Date().toISOString(),
          what,
          matched,
          // The list view is capped at 1000 rows per call by design; saying how
          // many rows matched stops the file from looking complete when it is not.
          returned: rows.length,
          result: rows,
        },
        { headers: { "content-disposition": attachment(`catalogue-${stamp()}.json`) } },
      );
    }
    const csv = toCsv(
      [
        "norad_id",
        "name",
        "cospar_id",
        "object_class",
        "country",
        "constellation",
        "regime",
        "purpose_group",
        "inclination_deg",
        "mass_kg",
        "hard_body_radius_m",
        "decay_date",
      ],
      rows.map((r) => [
        r.noradId,
        r.name,
        r.cosparId,
        r.objectClass,
        r.country,
        r.constellation,
        r.regime,
        r.purposeGroup,
        r.inclinationDeg,
        r.massKg,
        r.hardBodyRadiusM,
        r.decayDate,
      ]),
    );
    return new Response(csv, {
      headers: {
        "content-type": "text/csv; charset=utf-8",
        "content-disposition": attachment(`catalogue-${stamp()}.csv`),
        // The row cap is a fact about the file, so it travels with it.
        "x-matched-rows": String(matched),
        "x-returned-rows": String(rows.length),
      },
    });
  }

  if (what === "conjunctions") {
    const onlyUpcoming = url.searchParams.get("upcoming") === "1";
    const rows = listPublishedConjunctions(MAX_ROWS).filter((c) => (onlyUpcoming ? c.tcaInFuture : true));
    if (format === "json") {
      return NextResponse.json(
        { exported_at: new Date().toISOString(), what, count: rows.length, result: rows },
        { headers: { "content-disposition": attachment(`conjunctions-${stamp()}.json`) } },
      );
    }
    const csv = toCsv(
      [
        "cdm_id",
        "created_at",
        "tca",
        "probability_of_collision",
        "miss_distance_km",
        "message_count",
        "object1_norad",
        "object1_name",
        "object2_norad",
        "object2_name",
        "tca_in_future",
      ],
      rows.map((c) => [
        c.cdmId,
        c.createdIso,
        c.tcaIso,
        c.pc,
        c.minRangeKm,
        c.messageCount,
        c.object1Norad,
        c.object1Name,
        c.object2Norad,
        c.object2Name,
        c.tcaInFuture,
      ]),
    );
    return new Response(csv, {
      headers: {
        "content-type": "text/csv; charset=utf-8",
        "content-disposition": attachment(`conjunctions-${stamp()}.csv`),
      },
    });
  }

  return NextResponse.json(
    { error: `unknown what "${what}"; expected objects, catalogue or conjunctions` },
    { status: 400 },
  );
}
